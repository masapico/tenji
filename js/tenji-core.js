/**
 * 単一マスの点字（6桁文字列）から該当する文字・記号を取得します。
 * プレフィックス記号の場合は「組合せに利用する点」と返します。
 *
 * @param {string} value - 6桁の点字バイナリ文字列（例: "100000"）
 * @returns {string | undefined} 対応する文字、説明、または未定義
 */
export const identifyTenji = (value) => {
  if (TenjiMap[value]) {
    const char = TenjiMap[value];
    if (char.startsWith("cmb")) {
      return "組合せに利用する点";
    } else {
      return TenjiMap[value];
    }
  }
  return undefined;
};

/**
 * 複数マスの点字列（6桁文字列の配列）を解析し、濁点・拗音の合成を考慮してひらがな配列に変換します。
 *
 * @param {string[]} values - 点字バイナリ文字列の配列（例: ["000010", "100001"]）
 * @returns {string[]} 各マス位置に対応するひらがなの配列（結合記号の前置マスは全角空白 "　"）
 */
export const identifyTenjiArray = (values) => {
  const chars = [];
  const cmb = [];

  values.forEach((value) => {
    if (TenjiMap[value]) {
      const char = TenjiMap[value];
      if (char.startsWith("cmb")) {
        // 濁点・拗音などの前置記号を保持し、このマスは空白プレースホルダとする
        cmb.push(value);
        chars.push("　");
      } else {
        if (cmb.length !== 0) {
          // 組合せパターンの値（前置6桁 + 現在6桁 = 12桁）
          const cmbValue = `${cmb[0]}${value}`;
          cmb.pop(); // 組合せ判定後に消費
          if (TenjiCombinationMap[cmbValue]) {
            chars.push(TenjiCombinationMap[cmbValue]);
          } else {
            chars.push(char);
          }
        } else {
          chars.push(char);
        }
      }
    } else {
      // TenjiMapに存在しない場合（全て0など）
      chars.push("　");
    }
  });

  return chars;
};

/**
 * 日本語（ひらがな）文字列から、対応する点字バイナリ列（6桁文字列の配列）を生成します。
 * 濁音・拗音などの2マス合成音は2つの6桁文字列に展開されます。
 *
 * @param {string} words - ひらがな文字列（例: "がっこう"）
 * @returns {string[]} 6桁点字バイナリの配列（例: ["000010", "100001", "010000", "010101", "100100"]）
 */
export const getTenjiValues = (words) => {
  if (!words || typeof words !== "string") {
    return [];
  }

  // 処理に影響のある空白文字を一旦除去
  const regexSpace = /\s/g;
  let tmp = words.replace(regexSpace, "");

  // 1. 2マスで表現される組合せ音（濁音・拗音・特殊音など）を優先して展開
  const cmbKeys = Object.keys(TenjiCombinationMap);
  cmbKeys.forEach((key) => {
    const textTarget = TenjiCombinationMap[key];
    if (tmp.includes(textTarget)) {
      // 12桁を「前置6桁 + 半角空白 + 後続6桁 + 半角空白」に置換
      const replaceValue = `${key.substring(0, 6)} ${key.substring(6, key.length)} `;
      const regex = new RegExp(textTarget, "g");
      tmp = tmp.replace(regex, replaceValue);
    }
  });

  // 2. 1マスで表現される清音・記号を展開
  const keys = Object.keys(TenjiMap);
  keys.forEach((key) => {
    const textTarget = TenjiMap[key];
    if (tmp.includes(textTarget)) {
      const regex = new RegExp(textTarget, "g");
      tmp = tmp.replace(regex, `${key} `);
    }
  });

  // 3. マッピングにない文字（半角数字とスペース以外）は空白マス "000000 " に置換
  const regexNotNumber = /[^0-9 ]/g;
  tmp = tmp.replace(regexNotNumber, "000000 ");

  const trimmed = tmp.trim();
  if (trimmed.length === 0) {
    return [];
  }

  return trimmed.split(/\s+/);
};

